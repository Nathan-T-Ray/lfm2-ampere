#!/usr/bin/env python3
"""Generate src/tensor_table.h from the pack manifest.

A generated header beats a runtime format here: zero serialisation mismatch
risk, trivially inspectable, and the engine needs no parser at all.

For multi-expert tensors (dims [K, N, E]) the flat block layout is
    flat_row = expert * N + row          (block index = flat_row * bpr + k)
which is exactly ggml's ne0-fastest ordering.
"""
import json
import os
import pathlib
import sys

PLANE_ORDER = {"F32": ["data"], "Q4_0": ["qs", "d"], "Q6_K": ["ql", "qh", "scales", "d"]}


def main():
    man = json.loads(pathlib.Path(os.environ["LK_MANIFEST"]).read_text())
    out = pathlib.Path(__file__).resolve().parent.parent / "src" / "tensor_table.h"
    L = []
    L.append("// GENERATED by tools/gen_tensor_table.py -- do not edit by hand.")
    L.append("// Offsets are absolute byte offsets into lfm25.pack.")
    L.append("#pragma once")
    L.append("#include <cstdint>")
    L.append("#include <cstring>")
    L.append("")
    L.append("struct LKTensor {")
    L.append("    const char * name;")
    L.append("    uint32_t ggml_type;      // 0=F32, 2=Q4_0, 14=Q6_K")
    L.append("    uint32_t n_planes;")
    L.append("    uint64_t nelem;")
    L.append("    uint32_t cols;           // dims[0] (fastest-varying / input dim)")
    L.append("    uint32_t rows;           // nelem / cols; for experts this is E*N")
    L.append("    uint32_t blocks_per_row;")
    L.append("    uint32_t block_elems;")
    L.append("    uint64_t plane[4];       // byte offsets, in PLANE_ORDER")
    L.append("};")
    L.append("")
    L.append("static const LKTensor LK_TENSORS[] = {")
    type_id = {"F32": 0, "Q4_0": 2, "Q6_K": 14}
    for t in sorted(man["tensors"], key=lambda x: x["src_offset"]):
        po = PLANE_ORDER[t["type_name"]]
        offs = [t["planes"][p]["offset"] for p in po]
        while len(offs) < 4:
            offs.append(0)
        L.append('    {"%s", %d, %d, %dull, %d, %d, %d, %d, {%s}},'
                 % (t["name"], type_id[t["type_name"]], len(po), t["nelem"],
                    t["cols"], t["rows"], t["blocks_per_row"], t["block_elems"],
                    ", ".join("%dull" % o for o in offs)))
    L.append("};")
    L.append("static const int LK_N_TENSORS = %d;" % len(man["tensors"]))
    L.append("")
    L.append("static inline const LKTensor * lk_find(const char * n) {")
    L.append("    for (int i = 0; i < LK_N_TENSORS; ++i)")
    L.append("        if (strcmp(LK_TENSORS[i].name, n) == 0) return &LK_TENSORS[i];")
    L.append("    return nullptr;")
    L.append("}")
    L.append("")
    out.write_text("\n".join(L))
    print(f"wrote {out} ({out.stat().st_size:,} bytes, {len(man['tensors'])} tensors)")


if __name__ == "__main__":
    main()
